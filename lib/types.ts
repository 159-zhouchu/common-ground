export type StrategyId = 'S0' | 'S1' | 'S5';
export type Source = {
  id: string;
  name: string;
  version: number;
  text: string;
  createdAt: string;
  kind: 'original';
  warning?: string;
  history?: { version: number; text: string; createdAt: string }[];
};
export type Block = { id: string; title: string; content: string; origin: 'user' | 'ai' | 'demo' };
export type Revision = {
  id: string;
  number: number;
  title: string;
  blocks: Block[];
  constraint: string;
  createdAt: string;
  reason: string;
  parentId?: string;
};
export type Finding = {
  id: string;
  title: string;
  kind: string;
  severity: 'high' | 'medium' | 'low';
  blockId: string;
  before: string;
  after: string;
  reason: string;
  sourceId: string;
  sourceVersion?: number;
  quote: string;
  relation: 'supports' | 'contradicts' | 'insufficient';
  quoteValid: boolean;
  status: 'pending' | 'accepted' | 'rejected' | 'deferred';
  baseRevision: string;
  stale: boolean;
  runId: string;
  responder?: string;
  appliedRevision?: string;
};
export type Message = {
  id: string;
  actor: 'user' | 'assistant';
  content: string;
  model?: string;
  createdAt: string;
  runId?: string;
};
export type Manifest = {
  goal: string;
  constraint: string;
  sources: { id: string; version: number; text: string }[];
  blocks: Block[];
  messages: Message[];
  mode: 'continue' | 'source_only';
  excluded: string[];
  priorOutputs?: Review[];
  hash: string;
};
export type ConnectionSnapshot = {
  connectionId: string;
  label: string;
  model: string;
  protocol: 'chat' | 'responses';
  baseURL: string;
  updatedAt: string | null;
  structured: boolean;
  inputPrice: number | null;
  outputPrice: number | null;
};
export type RoleAssignments = { a: string; b?: string };
export type Step = {
  connectionId?: string;
  connectionSnapshot?: ConnectionSnapshot;
  id: string;
  label: string;
  slot: 'a' | 'b' | 'demo';
  duty: string;
  status: 'queued' | 'running' | 'completed' | 'failed' | 'cancelled';
  result?: string;
  error?: string;
  manifest?: Manifest;
  inputHash?: string;
  startedAt?: string;
  endedAt?: string;
  model?: string;
  usage?: { input: number | null; output: number | null; raw: unknown };
  cost: number | null;
  output?: Review;
  requestId?: string;
  sent?: boolean;
};
export type Run = {
  discussionQuestion?: string;
  roleAssignments?: RoleAssignments;
  connectionSnapshots?: ConnectionSnapshot[];
  compareRole?: 'a' | 'b';
  id: string;
  strategy: StrategyId;
  selfCheck: boolean;
  mode: 'demo' | 'live';
  contextMode: 'continue' | 'source_only';
  baseRevision: string;
  branch: string;
  state: 'running' | 'succeeded' | 'partial' | 'failed' | 'cancelled' | 'interrupted';
  steps: Step[];
  createdAt: string;
  endedAt?: string;
  summary: string;
  limit: number;
  findings: string[];
  error?: string;
  slot: 'a' | 'b';
  deadline: number;
  budget: number | null;
};
export type Impact = {
  id: string;
  blockId: string;
  title: string;
  state: 'review' | 'possible' | 'unchecked' | 'checked';
  reason: string;
  rule: string;
  createdAt: string;
};
export type Task = {
  id: string;
  title: string;
  description: string;
  goal: string;
  example: boolean;
  currentRevision: string;
  revisions: Revision[];
  sources: Source[];
  findings: Finding[];
  messages: Message[];
  runs: Run[];
  impacts: Impact[];
  createdAt: string;
  updatedAt: string;
};
export type Store = { version: 1; tasks: Task[]; archivedTasks?: Task[] };
export type Connection = {
  connectionId: string;
  enabled: boolean;
  createdAt: string | null;
  updatedAt: string | null;
  slot?: 'a' | 'b';
  label: string;
  baseURL: string;
  apiKey: string;
  model: string;
  protocol: 'chat' | 'responses';
  structured: boolean;
  inputPrice: number | null;
  outputPrice: number | null;
};
export type Review = {
  summary: string;
  findings: {
    title: string;
    kind: string;
    severity: 'high' | 'medium' | 'low';
    blockId: string;
    before: string;
    after: string;
    reason: string;
    sourceId: string;
    quote: string;
    relation: 'supports' | 'contradicts' | 'insufficient';
  }[];
  questions: string[];
};
export type LegacyConnection = Omit<
  Connection,
  'connectionId' | 'enabled' | 'createdAt' | 'updatedAt'
> & { slot: 'a' | 'b' };
export type ConnectionTest = {
  id: string;
  connectionId?: string;
  slot?: string;
  model: string;
  baseURL: string;
  protocol: string;
  startedAt: string;
  latencyMs: number;
  success: boolean;
  code?: string;
  input: number | null;
  output: number | null;
  cost: number | null;
  configUpdatedAt?: string | null;
};
export type PublicConnection = Omit<Connection, 'apiKey'> & {
  configured: boolean;
  hasKey: boolean;
  inUse: boolean;
  lastTest: ConnectionTest | null;
};
export type RunOptions = {
  roleAssignments?: RoleAssignments;
  compareRole?: 'a' | 'b';
  strategy: StrategyId;
  selfCheck: boolean;
  mode: 'demo' | 'live';
  contextMode: 'continue' | 'source_only';
  slot: 'a' | 'b';
  budget: number | null;
};
